    private void addButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addButtonActionPerformed
        boolean noErrors = false;
        this.patientIDLabel.setForeground(Color.black);
                
        if(!nullOrEmpty(this.patientIdTextField.getText())){
            noErrors = true;
        }else{
            this.patientIDLabel.setForeground(Color.red);
            noErrors = false;
        }
        
        if(noErrors){
            this.createPatient = new CreatePatient();
            this.createPatient.setPatientId(this.patientIdTextField.getText());
            this.createPatient.setTarget(this.targetTextArea.getText());
            this.setVisible(false);
        }
    }//GEN-LAST:event_addButtonActionPerformed

