    private boolean nullOrEmpty(String value){
        if(value == null){
            return true;
        }else if(value.length() < 1){
            return true;
        }
        return false;
    }
    
    public void setCreatePatient(CreatePatient patient){
        if(patient.getPatientId() != null){
            this.patientIdTextField.setText(patient.getPatientId());
        }
        
        if(patient.getTarget() != null){
            this.targetTextArea.setText(patient.getTarget());
        }
        
        this.addButton.setEnabled(false);
        this.addButton.setVisible(false);
    }
    
    public CreatePatient getCreatePatient(){
        return this.createPatient;
    }
    
    
